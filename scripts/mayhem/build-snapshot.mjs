import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { aggregateMayhemRecords } from './aggregate.mjs'
import { argValue, hasFlag } from './shared.mjs'

// snapshot.ts 的 aggregateMayhemRecords 是权威实现；本脚本经 ./aggregate.mjs 复用同一套
// 聚合/去重/off-meta 门槛逻辑（JS 镜像），由 snapshot.test.ts 的 parity 测试守护一致性。
// 本脚本只负责：读缓存数据 → 推导 source 健康 → 调聚合 → 写 snapshot.json + mayhemSnapshot.ts。

const scriptDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(scriptDir, '..', '..')

function quote(value) {
  return `'${String(value)
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('\r', '\\r')
    .replaceAll('\n', '\\n')}'`
}

async function readJson(path) {
  return JSON.parse(await readFile(path, 'utf8'))
}

function isUnavailable(payload) {
  return payload && typeof payload === 'object' && payload.status === 'unavailable'
}

function collectAggregateSource(sourceId, payload) {
  // Honest health: an {status:'unavailable'} stub contributes NO records and is offline.
  if (isUnavailable(payload)) {
    return {
      health: {
        sourceId,
        kind: 'aggregate',
        status: 'offline',
        reason: payload.reason ?? 'unavailable',
        ...(payload.sourceUrl ? { sourceUrl: payload.sourceUrl } : {}),
      },
      records: [],
    }
  }

  const records = Array.isArray(payload?.records) ? payload.records : []
  return {
    health: {
      sourceId,
      kind: 'aggregate',
      status: 'online',
      ...(payload?.meta?.sourceUrl ? { sourceUrl: payload.meta.sourceUrl } : {}),
    },
    records,
  }
}

function renderTs(snapshot) {
  return `// AUTO-GENERATED by scripts/mayhem/build-snapshot.mjs. Do not edit by hand.
// Run \`node scripts/mayhem/build-snapshot.mjs --patch ${snapshot.patch}\` to regenerate.
import type { MayhemSnapshot } from '../features/mayhem/snapshot'

export const mayhemSnapshot: MayhemSnapshot = ${JSON.stringify(snapshot, null, 2)} as const

export default mayhemSnapshot
`
}

// Normalize away volatile timestamps for --check comparison.
function stripVolatile(text) {
  return text
    .replace(/"generatedAt": "[^"]*"/g, '"generatedAt": "<volatile>"')
    .replace(/"expiresAt": "[^"]*"/g, '"expiresAt": "<volatile>"')
    .replaceAll('\r\n', '\n')
}

const patch = argValue('--patch', '26.12')
const check = hasFlag('--check')

const dataDir = resolve(repoRoot, 'data', 'mayhem', patch)
const jsonOutput = resolve(dataDir, 'snapshot.json')
const tsOutput = resolve(repoRoot, 'src', 'data', 'mayhemSnapshot.ts')

const official = await readJson(resolve(dataDir, 'official-augments.json'))
const metasrc = await readJson(resolve(dataDir, 'metasrc.json'))
const opgg = await readJson(resolve(dataDir, 'opgg.json'))
const community = await readJson(resolve(dataDir, 'community-candidates.json'))

const augments = official.augments.map((augment) => ({
  id: augment.id,
  apiName: augment.apiName,
  name: augment.name,
  rarity: augment.rarity,
  description: augment.description,
  iconUrl: augment.iconUrl,
}))
const officialAugmentIds = augments.map((augment) => augment.id)

const sources = []
const aggregateRecords = []

sources.push({
  sourceId: 'communitydragon',
  kind: 'official',
  status: 'online',
  sourceUrl: official.meta?.sourceUrl,
})

for (const [sourceId, payload] of [
  ['metasrc', metasrc],
  ['opgg', opgg],
]) {
  const collected = collectAggregateSource(sourceId, payload)
  sources.push(collected.health)
  aggregateRecords.push(...collected.records)
}

const communityCandidates = Array.isArray(community?.candidates) ? community.candidates : []
sources.push({
  sourceId: 'community',
  kind: 'community',
  status: communityCandidates.length > 0 ? 'online' : 'offline',
  reason: communityCandidates.length > 0 ? undefined : 'no candidates collected',
})

const snapshot = aggregateMayhemRecords({
  patch,
  officialAugmentIds,
  records: aggregateRecords,
  augments,
  sources,
})

const tsOutputText = renderTs(snapshot)

if (check) {
  const currentTs = await readFile(tsOutput, 'utf8')
  if (stripVolatile(currentTs) !== stripVolatile(tsOutputText)) {
    throw new Error(`${tsOutput} is out of date. Run node scripts/mayhem/build-snapshot.mjs --patch ${patch}.`)
  }
  console.log(`Checked ${tsOutput} (patch ${patch}) — up to date.`)
} else {
  await mkdir(dirname(jsonOutput), { recursive: true })
  await mkdir(dirname(tsOutput), { recursive: true })
  await writeFile(jsonOutput, `${JSON.stringify(snapshot, null, 2)}\n`)
  await writeFile(tsOutput, tsOutputText)
  console.log(
    `Generated ${jsonOutput} and ${tsOutput} (patch ${patch}): ${augments.length} augments, ` +
      `${snapshot.recommendations.strength.length} strength, ${snapshot.recommendations.offMeta.length} offMeta, ` +
      `completeness ${snapshot.completeness}, officialCoverage ${snapshot.officialCoverage}.`,
  )
}
